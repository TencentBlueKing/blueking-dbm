func TestApplyClusterNoFailoverToConf(t *testing.T) {
	// 空载起进程期间被 cluster 自动 failover 选上, 它负责的 slot 会连带数据一起变空
	job := buildRegenJob("1.1.1.1", []int{30000})
	job.params.Pkg = "redis-6.2.7.tar.gz"
	job.params.ClusterType = consts.TendisTypePredixyRedisCluster
	job.discardPorts = map[int]bool{30000: true}

	got := job.applyReplExpectationToConf(30000, "port 30000\ncluster-replica-no-failover no\n")
	if !strings.Contains(got, "cluster-replica-no-failover yes") {
		t.Errorf("conf should forbid failover while syncing from scratch:\n%s", got)
	}
	if strings.Contains(got, "cluster-replica-no-failover no") {
		t.Errorf("stale directive should have been replaced:\n%s", got)
	}

	// redis 4 只认 slave 系列写法, 写错名字实例直接起不来
	job.params.Pkg = "redis-4.11.6.tar.gz"
	got = job.applyReplExpectationToConf(30000, "port 30000\n")
	if !strings.Contains(got, "cluster-slave-no-failover yes") {
		t.Errorf("conf should use the 4.x spelling:\n%s", got)
	}

	// 不空载起进程时不该动这一项
	job.discardPorts = map[int]bool{}
	if got = job.applyReplExpectationToConf(30000, "port 30000\n"); strings.Contains(got, "no-failover") {
		t.Errorf("failover permission should be untouched:\n%s", got)
	}
}

func TestRenderTargetConfWritesSyncMaster(t *testing.T) {
	// 端到端: 目标版本配置渲染 + 写入新主库 + 自校验, 三者必须自洽
	job := buildRegenJob("1.1.1.1", []int{30000})
	job.params.Pkg = "redis-6.2.7.tar.gz"
	job.params.ClusterType = consts.TendisTypeTwemproxyRedisInstance
	job.params.SyncMasters = map[string]string{"30000": "1.1.1.2:30000"}
	// old_master 的配置里本来没有主从关系
	oldConf := "port 30000\ndir /data1/redis/30000/data\nrequirepass \"xxxxpasswd\"\nmaxmemory 8589934592\n"
	oldDirectives := redisconf.ParseDirectives(oldConf)

	got, err := job.renderTargetConf(
		30000, "/data1/redis/30000/redis.conf",
		redisconf.RenderItem{
			ConfConfigs: map[string]string{
				"port": "{{port}}", "dir": "{{redis_data_dir}}/data",
				"requirepass": "{{password}}", "maxmemory": "{{maxmemory}}",
			},
			Databases: 2,
		},
		oldConf, oldDirectives,
	)
	if err != nil {
		t.Fatalf("renderTargetConf err:%v", err)
	}
	if !strings.Contains(got, "replicaof 1.1.1.2 30000") {
		t.Fatalf("rendered conf does not replicate from the new master:\n%s", got)
	}
	// 主从关系和它的认证是一对: 只写 replicaof 的话同步会卡在 AUTH 上
	if !strings.Contains(got, "masterauth xxxxpasswd") {
		t.Fatalf("rendered conf declares replication without masterauth:\n%s", got)
	}
	if lastDirective(got, "appendonly") != "yes" {
		t.Fatalf("old_master becoming replica must enable aof, last appendonly=%q\ngot:\n%s",
			lastDirective(got, "appendonly"), got)
	}
	if err = job.validateRegenConf(
		30000, "/data1/redis/30000/redis.conf", got, oldConf, oldDirectives); err != nil {
		t.Errorf("rendered conf failed its own validation:%v", err)
	}
}

