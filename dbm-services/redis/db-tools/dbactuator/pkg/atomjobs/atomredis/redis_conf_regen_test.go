func TestApplyReplExpectationToConf(t *testing.T) {
	// old_master 升级: 配置里原本没有主从关系(它自己就是主), 重建时要写进 replicaof new_master
	cases := []struct {
		name        string
		pkg         string
		clusterType string
		conf        string
		want        string
		notWant     string
	}{
		{
			name: "redis 6 gets replicaof",
			pkg:  "redis-6.2.7.tar.gz",
			conf: "port 30000\n",
			want: "replicaof 1.1.1.2 30000",
		},
		{
			// replicaof 是 redis 5.0 才有的别名, 更老的版本认了这行会直接起不来
			name:    "redis 4 gets slaveof",
			pkg:     "redis-4.11.6.tar.gz",
			conf:    "port 30000\n",
			want:    "slaveof 1.1.1.2 30000",
			notWant: "replicaof",
		},
		{
			name:    "version unparseable falls back to slaveof",
			pkg:     "redis-unknown.tar.gz",
			conf:    "port 30000\n",
			want:    "slaveof 1.1.1.2 30000",
			notWant: "replicaof",
		},
		{
			// 继承下来的那条指向老主库, 必须被顶掉而不是留在文件里
			name:    "stale replication line replaced",
			pkg:     "redis-6.2.7.tar.gz",
			conf:    "port 30000\nslaveof 3.3.3.3 30000\n",
			want:    "replicaof 1.1.1.2 30000",
			notWant: "3.3.3.3",
		},
		{
			// cluster 架构的主从关系在 nodes.conf 里, 配置文件写 replicaof 没有意义
			name:        "cluster type writes nothing",
			pkg:         "redis-6.2.7.tar.gz",
			clusterType: consts.TendisTypePredixyRedisCluster,
			conf:        "port 30000\n",
			notWant:     "replicaof",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			job := buildRegenJob("1.1.1.1", []int{30000})
			job.params.Pkg = tc.pkg
			job.params.ClusterType = tc.clusterType
			if job.params.ClusterType == "" {
				job.params.ClusterType = consts.TendisTypeTwemproxyRedisInstance
			}
			job.params.SyncMasters = map[string]string{"30000": "1.1.1.2:30000"}

			got := job.applyReplExpectationToConf(30000, tc.conf)
			if tc.want != "" && !strings.Contains(got, tc.want) {
				t.Errorf("conf missing %q:\n%s", tc.want, got)
			}
			if tc.notWant != "" && strings.Contains(got, tc.notWant) {
				t.Errorf("conf should not contain %q:\n%s", tc.notWant, got)
			}
			if tc.want != "" {
				if count := strings.Count(got, "slaveof ") + strings.Count(got, "replicaof "); count != 1 {
					t.Errorf("replication directive appears %d times, want exactly 1:\n%s", count, got)
				}
			}
		})
	}
}

func lastDirective(conf, name string) string {
	return redisconf.Unquote(redisconf.ParseDirectives(conf).LastValue(name))
}

// regenConfWithBind 一份最小的合法重建结果, bindLine 为空时整条 bind 都不写
func regenConfWithBind(bindLine string) string {
	rest := strings.Join([]string{
		"port 30000",
		"dir /data1/redis/30000/data",
		"requirepass \"xxxxpasswd\"",
		"masterauth \"xxxxpasswd\"",
		"replicaof 1.1.1.2 30000",
	}, "\n") + "\n"
	if bindLine == "" {
		return rest
	}
	return bindLine + "\n" + rest
}

func TestValidateRegenConfBind(t *testing.T) {
	// 旧现场绑的是本机 IP (liveConfAfterConfigRewrite 里的 bind 1.1.1.1)
	oldConf := liveConfAfterConfigRewrite
	oldDirectives := redisconf.ParseDirectives(oldConf)
	job := buildRegenJob("1.1.1.1", []int{30000})

	cases := []struct {
		name    string
		bind    string
		wantErr string
	}{
		{name: "unchanged", bind: "bind 1.1.1.1"},
		// 存量实例磁盘上只有 bind <ip>, 目标模板是 {{address}} 127.0.0.1: 新增不算事故
		{name: "extra loopback", bind: "bind 1.1.1.1 127.0.0.1"},
		{name: "order and quotes ignored", bind: "bind \"127.0.0.1\" \"1.1.1.1\""},
		// 前缀 '-' 只表示绑不上也不算启动失败, 说的还是同一个地址
		{name: "optional prefix", bind: "bind -1.1.1.1"},
		// 下发了别的机器的 IP: 实例绑不上本机地址, 起都起不来
		{name: "stale ip", bind: "bind 3.3.3.3", wantErr: "drops address(es) [1.1.1.1]"},
		{name: "all interfaces", bind: "bind 0.0.0.0", wantErr: "drops address(es) [1.1.1.1]"},
		{name: "loopback only", bind: "bind 127.0.0.1", wantErr: "drops address(es) [1.1.1.1]"},
		{name: "no bind at all", bind: "", wantErr: "listen on all interfaces"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			err := job.validateRegenConf(30000, "/data1/redis/30000/redis.conf",
				regenConfWithBind(tc.bind), oldConf, oldDirectives)
			if tc.wantErr == "" {
				if err != nil {
					t.Fatalf("valid bind rejected:%v", err)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
				t.Errorf("err = %v, want it to contain %q", err, tc.wantErr)
			}
		})
	}

	// 旧配置压根没有 bind 时无从比较, 跳过而不是拦下
	noBindOld := strings.Replace(oldConf, "bind 1.1.1.1\n", "", 1)
	if err := job.validateRegenConf(30000, "/data1/redis/30000/redis.conf",
		regenConfWithBind("bind 3.3.3.3"), noBindOld, redisconf.ParseDirectives(noBindOld)); err != nil {
		t.Errorf("old conf without bind should skip the check:%v", err)
	}
}

