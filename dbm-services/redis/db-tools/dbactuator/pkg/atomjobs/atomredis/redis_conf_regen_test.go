func TestRegenConfKeepsDataDirSpellingUnderSymlink(t *testing.T) {
	// 复现线上现场: /data1 -> /data, 实例配置里写的是 /data, 而 GetRedisDataDir()
	// 只要看到 /data1/redis 就返回 /data1. 重建后不能把 dir 改成 /data1 的写法.
	realDataDir, aliasDataDir := setupAliasedDataDir(t, 30000)
	t.Setenv("REDIS_DATA_DIR", aliasDataDir)

	realInstDir := filepath.Join(realDataDir, "redis", "30000")
	confFile := filepath.Join(realInstDir, "redis.conf")
	liveConf := strings.Join([]string{
		"port 30000",
		"requirepass \"xxxxpasswd\"",
		"dir \"" + filepath.Join(realInstDir, "data") + "\"",
		"maxmemory 8589934592",
		"replicaof 1.1.1.2 30000",
	}, "\n") + "\n"
	if err := os.WriteFile(confFile, []byte(liveConf), 0644); err != nil {
		t.Fatalf("write conf failed:%v", err)
	}

	job := buildRegenJob("1.1.1.1", []int{30000})
	job.params.PortConfConfigs = map[string]RedisConfRenderItem{"30000": targetConfItem(realInstDir)}
	if err := job.regenConfFile(30000); err != nil {
		t.Fatalf("regenConfFile err:%v", err)
	}

	got, err := os.ReadFile(confFile)
	if err != nil {
		t.Fatalf("read conf failed:%v", err)
	}
	wantDir := "dir " + filepath.Join(realInstDir, "data")
	if !strings.Contains(string(got), wantDir+"\n") {
		t.Errorf("regenerated conf lost the old data dir spelling, want %q:\n%s", wantDir, got)
	}
	if strings.Contains(string(got), aliasDataDir) {
		t.Errorf("regenerated conf switched to the symlink alias %q:\n%s", aliasDataDir, got)
	}
}

func TestPrecheckConfRegenFailsWithoutTouchingConf(t *testing.T) {
	// 下发的配置项不全(同版本升级只继承少量配置项)时, 必须在停实例之前就失败,
	// 而且不能改动线上配置文件
	confFile := setupInstanceConf(t, 30000, "placeholder\n")
	instDir := filepath.Dir(confFile)
	liveConf := liveConfForInstDir(instDir)
	if err := os.WriteFile(confFile, []byte(liveConf), 0644); err != nil {
		t.Fatalf("rewrite conf failed:%v", err)
	}

	job := buildRegenJob("1.1.1.1", []int{30000})
	job.params.PortConfConfigs = map[string]RedisConfRenderItem{
		"30000": {ConfConfigs: map[string]string{"maxmemory": "{{maxmemory}}"}, Databases: 2},
	}
	err := job.precheckConfRegen([]int{30000})
	if err == nil {
		t.Fatal("precheck should reject an incomplete conf")
	}
	if !strings.Contains(err.Error(), "not a complete redis.conf") {
		t.Errorf("err = %v, want it to explain the conf is incomplete", err)
	}
	got, readErr := os.ReadFile(confFile)
	if readErr != nil {
		t.Fatalf("read conf failed:%v", readErr)
	}
	if string(got) != liveConf {
		t.Errorf("precheck modified live conf:\n%s", got)
	}
	if _, statErr := os.Stat(confFile + ".new"); statErr == nil {
		t.Error("precheck should not write redis.conf.new")
	}
	if len(job.confBackupFiles) != 0 {
		t.Errorf("precheck should not record a backup, got %+v", job.confBackupFiles)
	}
}

