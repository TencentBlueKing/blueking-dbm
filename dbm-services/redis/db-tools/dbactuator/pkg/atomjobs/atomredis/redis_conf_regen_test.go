func TestRenderTargetConfEndToEnd(t *testing.T) {
	// 目标版本模板: 去掉了旧版本的 slave-lazy-flush (改名为 replica-lazy-flush),
	// maxmemory / dir / password 走占位符
	targetConfConfigs := map[string]string{
		"bind":               "{{address}}",
		"port":               "{{port}}",
		"requirepass":        "{{password}}",
		"dir":                "{{redis_data_dir}}/data",
		"logfile":            "{{redis_data_dir}}/redis.log",
		"databases":          "{{databases}}",
		"maxmemory":          "{{maxmemory}}",
		"appendonly":         "no",
		"replica-lazy-flush": "yes",
		"rename-command":     "config confxx \nrename-command flushdb cleandb \nrename-command flushall cleanall",
		"save":               "3600 1\nsave 300 100",
	}
	job := buildRegenJob("1.1.1.1", []int{30000})
	oldConf := liveConfAfterConfigRewrite
	oldDirectives := redisconf.ParseDirectives(oldConf)

	got, err := job.renderTargetConf(
		30000, "/data1/redis/30000/redis.conf",
		redisconf.RenderItem{ConfConfigs: targetConfConfigs, Databases: 2},
		oldConf, oldDirectives,
	)
	if err != nil {
		t.Fatalf("renderTargetConf err:%v", err)
	}

	// 目标版本不再有的指令自然消失 —— 这正是新版本进程起不来的根因所在
	if strings.Contains(got, "slave-lazy-flush") {
		t.Errorf("stale directive slave-lazy-flush should be dropped\ngot:\n%s", got)
	}
	if !strings.Contains(got, "replica-lazy-flush yes") {
		t.Errorf("target directive replica-lazy-flush missing\ngot:\n%s", got)
	}
	// 运行态取值必须沿用磁盘上的
	if !strings.Contains(got, "maxmemory 8589934592") {
		t.Errorf("maxmemory reset instead of carried over\ngot:\n%s", got)
	}
	if !strings.Contains(got, "dir /data1/redis/30000/data") {
		t.Errorf("non-standard data dir not respected\ngot:\n%s", got)
	}
	if !strings.Contains(got, "requirepass xxxxpasswd") {
		t.Errorf("password not taken from disk\ngot:\n%s", got)
	}
	if !strings.Contains(got, "replicaof 1.1.1.2 30000") {
		t.Errorf("replicaof not carried over\ngot:\n%s", got)
	}
	if lastDirective(got, "appendonly") != "no" {
		t.Errorf("old slave carry-over replicaof must not force aof, last appendonly=%q\ngot:\n%s", lastDirective(got, "appendonly"), got)
	}
	// 可重复指令保持展开
	if count := strings.Count(got, "rename-command "); count != 3 {
		t.Errorf("rename-command lines = %d, want 3\ngot:\n%s", count, got)
	}

	if err = job.validateRegenConf(
		30000, "/data1/redis/30000/redis.conf", got, oldConf, oldDirectives); err != nil {
		t.Errorf("rendered conf failed validation:%v", err)
	}
}

