// liveConfAfterConfigRewrite 一份 config rewrite 之后的 redis.conf 片段.
// 特点: 指令顺序被重排, 可重复指令是多行, maxmemory / replicaof 是运行态写进去的.
const liveConfAfterConfigRewrite = `# Redis configuration rewritten by CONFIG REWRITE
bind 1.1.1.1
port 30000
requirepass "xxxxpasswd"
masterauth "xxxxpasswd"
dir /data1/redis/30000/data
logfile /data1/redis/30000/redis.log
databases 2
maxmemory 8589934592
appendonly no
slave-lazy-flush yes
rename-command config confxx
rename-command flushdb cleandb
rename-command flushall cleanall
save 3600 1
save 300 100
client-output-buffer-limit normal 256mb 512mb 300
client-output-buffer-limit slave 2048mb 2048mb 300

# Generated by CONFIG REWRITE
replicaof 1.1.1.2 30000
`

// buildRegenJob 构造一个测试用 job. util.RunBashCmd 走的是包级 mylog.Logger, 也要一并初始化
func buildRegenJob(ip string, ports []int) *RedisVersionUpdate {
	testLogger := logger.New(io.Discard, false, logger.InfoLevel)
	mylog.SetDefaultLogger(testLogger)
	return &RedisVersionUpdate{
		runtime:       &jobruntime.JobGenericRuntime{Logger: testLogger},
		params:        RedisVersionUpdateParams{IP: ip, Ports: ports},
		replSnapshots: map[int]replSnapshot{},
		discardPorts:  map[int]bool{},
		offline:       map[int]*redisconf.Applied{},
	}
}

// 下面几个方法是测试用的适配层: 把 job 上的参数拼成一次 redisconf.Request, 保留
// "给一份现场, 看渲染或校验结果" 的调用形状. 生产代码走 RedisVersionUpdate.regenRequest
// 再调 redisconf.Request.Plan, 这里只是省掉每个用例都手写一遍字段.

func (job *RedisVersionUpdate) regenReqForTest(
	port int, confFile, oldConfData string, item redisconf.RenderItem,
) redisconf.Request {
	req := job.regenRequest(port)
	req.Item = item
	req.ConfFile = confFile
	req.OldConfData = oldConfData
	return req
}

func (job *RedisVersionUpdate) instDirForRegen(port int, confFile string, oldConfData string) string {
	return job.regenReqForTest(port, confFile, oldConfData, redisconf.RenderItem{}).InstDir()
}

func (job *RedisVersionUpdate) renderTargetConf(
	port int, confFile string, item redisconf.RenderItem, oldConfData string, _ redisconf.Directives,
) (string, error) {
	return job.regenReqForTest(port, confFile, oldConfData, item).Render()
}

func (job *RedisVersionUpdate) validateRegenConf(
	port int, confFile string, confData string, oldConfData string, _ redisconf.Directives,
) error {
	return job.regenReqForTest(port, confFile, oldConfData, redisconf.RenderItem{}).Validate(confData)
}

// applyReplExpectationToConf 升级时与拓扑相关的两步改写: 主从关系和 cluster failover 开关
func (job *RedisVersionUpdate) applyReplExpectationToConf(port int, confData string) string {
	req := job.regenRequest(port)
	confData = redisconf.StepReplicaOf.Apply(req, confData)
	return redisconf.StepClusterNoFailover.Apply(req, confData)
}

func TestValidateRegenConf(t *testing.T) {
	oldConf := liveConfAfterConfigRewrite
	oldDirectives := redisconf.ParseDirectives(oldConf)
	goodConf := strings.Join([]string{
		"bind 1.1.1.1",
		"port 30000",
		"dir /data1/redis/30000/data",
		"requirepass \"xxxxpasswd\"",
		"masterauth \"xxxxpasswd\"",
		"replicaof 1.1.1.2 30000",
	}, "\n") + "\n"

	job := buildRegenJob("1.1.1.1", []int{30000})
	if err := job.validateRegenConf(
		30000, "/data1/redis/30000/redis.conf", goodConf, oldConf, oldDirectives); err != nil {
		t.Fatalf("valid conf rejected:%v", err)
	}

	cases := []struct {
		name    string
		conf    string
		wantErr string
	}{
		{
			name:    "leftover placeholder",
			conf:    strings.Replace(goodConf, "\"xxxxpasswd\"", "{{password}}", 1),
			wantErr: "unresolved placeholder",
		},
		{
			name:    "missing dir",
			conf:    "bind 1.1.1.1\nport 30000\nrequirepass \"xxxxpasswd\"\nreplicaof 1.1.1.2 30000\n",
			wantErr: "missing directive \"dir\"",
		},
		{
			name:    "wrong port",
			conf:    strings.Replace(goodConf, "port 30000", "port 30001", 1),
			wantErr: "mismatch",
		},
		{
			name:    "lost requirepass",
			conf:    strings.Replace(goodConf, "requirepass \"xxxxpasswd\"\n", "", 1),
			wantErr: "lost requirepass",
		},
		{
			name:    "changed requirepass",
			conf:    strings.Replace(goodConf, "requirepass \"xxxxpasswd\"", "requirepass otherpass", 1),
			wantErr: "would change requirepass",
		},
		{
			// 换个叶子目录, 而不是 /data1 -> /data: 后者在真有这条软链的机器上是同一目录
			name:    "moved data dir",
			conf:    strings.Replace(goodConf, "/data1/redis/30000/data", "/data1/redis/30000/data-moved", 1),
			wantErr: "would move dir",
		},
		{
			name:    "lost replication",
			conf:    strings.Replace(goodConf, "replicaof 1.1.1.2 30000\n", "", 1),
			wantErr: "lost replication",
		},
		{
			name:    "changed replication target",
			conf:    strings.Replace(goodConf, "replicaof 1.1.1.2 30000", "replicaof 3.3.3.3 30000", 1),
			wantErr: "lost replication",
		},
		{
			// 旧文件里根本没有 masterauth 之外的凭据变更时也要拦: 改了主从同步会认证失败
			name:    "changed masterauth",
			conf:    strings.Replace(goodConf, "masterauth \"xxxxpasswd\"", "masterauth otherpass", 1),
			wantErr: "would change masterauth",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			err := job.validateRegenConf(
				30000, "/data1/redis/30000/redis.conf", tc.conf, oldConf, oldDirectives)
			if err == nil {
				t.Fatalf("expected error containing %q, got nil", tc.wantErr)
			}
			if !strings.Contains(err.Error(), tc.wantErr) {
				t.Errorf("err = %v, want it to contain %q", err, tc.wantErr)
			}
		})
	}
}

// setupAliasedDataDir 造一份 /data1 -> /data 的现场: 返回真实数据盘与它的软链别名.
func setupAliasedDataDir(t *testing.T, port int) (realDataDir, aliasDataDir string) {
	t.Helper()
	root := t.TempDir()
	realDataDir = filepath.Join(root, "data")
	aliasDataDir = filepath.Join(root, "data1")
	if err := os.MkdirAll(filepath.Join(realDataDir, "redis", strconv.Itoa(port)), 0755); err != nil {
		t.Fatalf("mkdir failed:%v", err)
	}
	if err := os.Symlink(realDataDir, aliasDataDir); err != nil {
		t.Fatalf("symlink failed:%v", err)
	}
	return realDataDir, aliasDataDir
}

func TestInstDirForRegen(t *testing.T) {
	job := buildRegenJob("1.1.1.1", []int{30000})
	cases := []struct {
		name    string
		oldDir  string
		want    string
		comment string
	}{
		{
			// 配置文件是靠 /data1 找到的, 但 dir 里写的是 /data: 以 dir 为准,
			// 否则重建后整份配置的路径写法都会从 /data 变成 /data1
			name:   "keep spelling from old conf",
			oldDir: "dir \"/data/redis/30000/data\"\n",
			want:   "/data/redis/30000",
		},
		{
			name:   "tendisplus nested data dir",
			oldDir: "dir /data/redis/30000/data/db\n",
			want:   "/data/redis/30000",
		},
		{
			// 旧配置没有 dir 或不认识的形状时退回配置文件所在目录
			name:   "no dir in old conf",
			oldDir: "port 30000\n",
			want:   "/data1/redis/30000",
		},
		{
			name:   "dir not under redis/port",
			oldDir: "dir /somewhere/else\n",
			want:   "/data1/redis/30000",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := job.instDirForRegen(30000, "/data1/redis/30000/redis.conf", tc.oldDir)
			if got != tc.want {
				t.Errorf("instDirForRegen = %q, want %q", got, tc.want)
			}
		})
	}
}

func TestRegenConfKeepsDataDirSpellingUnderSymlink(t *testing.T) {
	// 复现线上现场: /data1 -> /data, 实例配置里写的是 /data, 而 GetRedisDataDir()
	// 只要看到 /data1/redis 就返回 /data1. 重建后不能把 dir 改成 /data1 的写法.
	realDataDir, aliasDataDir := setupAliasedDataDir(t, 30000)
	t.Setenv("REDIS_DATA_DIR", aliasDataDir)

	realInstDir := filepath.Join(realDataDir, "redis", "30000")
	confFile := filepath.Join(realInstDir, "redis.conf")
	liveConf := strings.Join([]string{
		"port 30000",
		"requirepass \"xxxxpasswd\"",
		"dir \"" + filepath.Join(realInstDir, "data") + "\"",
		"maxmemory 8589934592",
		"replicaof 1.1.1.2 30000",
	}, "\n") + "\n"
	if err := os.WriteFile(confFile, []byte(liveConf), 0644); err != nil {
		t.Fatalf("write conf failed:%v", err)
	}

	job := buildRegenJob("1.1.1.1", []int{30000})
	job.params.PortConfConfigs = map[string]redisconf.RenderItem{"30000": targetConfItem(realInstDir)}
	if err := job.applyOfflineChanges(30000); err != nil {
		t.Fatalf("regenConfFile err:%v", err)
	}

	got, err := os.ReadFile(confFile)
	if err != nil {
		t.Fatalf("read conf failed:%v", err)
	}
	wantDir := "dir " + filepath.Join(realInstDir, "data")
	if !strings.Contains(string(got), wantDir+"\n") {
		t.Errorf("regenerated conf lost the old data dir spelling, want %q:\n%s", wantDir, got)
	}
	if strings.Contains(string(got), aliasDataDir) {
		t.Errorf("regenerated conf switched to the symlink alias %q:\n%s", aliasDataDir, got)
	}
}

