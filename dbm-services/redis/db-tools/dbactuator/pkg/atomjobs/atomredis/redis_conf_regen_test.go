func TestAppendCarryOverDirectives(t *testing.T) {
	oldConf := liveConfAfterConfigRewrite
	oldDirectives := parseRedisConfDirectives(oldConf)

	// 目标版本模板里没有 replicaof / masterauth: 必须补回来, 否则从库重启会变主库
	got := appendCarryOverDirectives("port 30000\n", oldConf, oldDirectives)
	if !strings.Contains(got, "replicaof 1.1.1.2 30000") {
		t.Errorf("replicaof not carried over\ngot:\n%s", got)
	}
	if !strings.Contains(got, "masterauth \"xxxxpasswd\"") {
		t.Errorf("masterauth not carried over\ngot:\n%s", got)
	}

	// 渲染结果里已经有的指令不重复追加
	got = appendCarryOverDirectives(
		"port 30000\nmasterauth \"newpass\"\nreplicaof 3.3.3.3 30000\n", oldConf, oldDirectives)
	if count := strings.Count(got, "masterauth"); count != 1 {
		t.Errorf("masterauth appended %d times, want 1\ngot:\n%s", count, got)
	}
	if count := strings.Count(got, "replicaof"); count != 1 {
		t.Errorf("replicaof appended %d times, want 1\ngot:\n%s", count, got)
	}

	// 主库不该被补出主从关系
	masterConf := "port 30000\nslaveof no one\n"
	got = appendCarryOverDirectives("port 30000\n", masterConf, parseRedisConfDirectives(masterConf))
	if strings.Contains(got, "slaveof") {
		t.Errorf("master should not get slaveof\ngot:\n%s", got)
	}
}

func TestAppendCarryOverDirectivesMixedReplicationSpellings(t *testing.T) {
	// 线上现场: redis_replicaof 原子任务 echo 追加了 slaveof, 之后 config rewrite
	// 又写了一条 replicaof. 逐名补写会同时追加两条指向不同主库的行, 而 redis 只认
	// 最后一行 —— 等于随机挑了个主库, 拉起后链路照样 UP, 没人发现跟错了主.
	mixedConf := strings.Join([]string{
		"port 30000",
		"slaveof 2.2.2.2 30000",
		"",
		"# Generated by CONFIG REWRITE",
		"replicaof 1.1.1.2 30000",
	}, "\n") + "\n"

	got := appendCarryOverDirectives("port 30000\n", mixedConf, parseRedisConfDirectives(mixedConf))
	if count := strings.Count(got, "slaveof ") + strings.Count(got, "replicaof "); count != 1 {
		t.Errorf("replication directive appended %d times, want exactly 1\ngot:\n%s", count, got)
	}
	// 生效的是文件里最后那条, 指令名也要沿用它的写法(redis 5.0 以下不认 replicaof)
	if !strings.Contains(got, "replicaof 1.1.1.2 30000") {
		t.Errorf("carried over the wrong master\ngot:\n%s", got)
	}
	if _, value := effectiveReplicationOf(got); value != "1.1.1.2 30000" {
		t.Errorf("effective master in result = %q, want 1.1.1.2 30000\ngot:\n%s", value, got)
	}

	// 旧文件用的是 slaveof 时, 补写也必须用 slaveof
	oldSlaveofConf := "port 30000\nslaveof 1.1.1.2 30000\n"
	got = appendCarryOverDirectives("port 30000\n", oldSlaveofConf, parseRedisConfDirectives(oldSlaveofConf))
	if !strings.Contains(got, "slaveof 1.1.1.2 30000") || strings.Contains(got, "replicaof") {
		t.Errorf("carry over should keep the slaveof spelling\ngot:\n%s", got)
	}
}

// buildRegenJob 构造一个测试用 job. util.RunBashCmd 走的是包级 mylog.Logger, 也要一并初始化
func buildRegenJob(ip string, ports []int) *RedisVersionUpdate {
	testLogger := logger.New(io.Discard, false, logger.InfoLevel)
	mylog.SetDefaultLogger(testLogger)
	return &RedisVersionUpdate{
		runtime:         &jobruntime.JobGenericRuntime{Logger: testLogger},
		params:          RedisVersionUpdateParams{IP: ip, Ports: ports},
		confBackupFiles: map[int]string{},
		replSnapshots:   map[int]replSnapshot{},
		discardPorts:    map[int]bool{},
		discardedFiles:  map[int][]discardedDataFile{},
	}
}

// 下面四个方法是测试用的适配层: 把 job 上的参数拼成一次 confRegenRequest, 保留
// "给一份现场, 看渲染或校验结果" 的调用形状. 生产代码走 RedisVersionUpdate.regenRequest
// 再调 confRegenRequest 上的同名方法, 这里只是省掉每个用例都手写一遍字段.

func (job *RedisVersionUpdate) regenReqForTest(
	port int, confFile, oldConfData string, item RedisConfRenderItem,
) confRegenRequest {
	req := job.regenRequest(port)
	req.Item = item
	req.ConfFile = confFile
	req.OldConfData = oldConfData
	return req
}

func (job *RedisVersionUpdate) instDirForRegen(
	port int, confFile string, oldDirectives confDirectives,
) string {
	return job.regenReqForTest(port, confFile, "", RedisConfRenderItem{}).instDirForRegen(oldDirectives)
}

func (job *RedisVersionUpdate) renderTargetConf(
	port int, confFile string, item RedisConfRenderItem, oldConfData string, oldDirectives confDirectives,
) (string, error) {
	return job.regenReqForTest(port, confFile, oldConfData, item).renderTargetConf(oldDirectives)
}

func (job *RedisVersionUpdate) validateRegenConf(
	port int, confFile string, confData string, oldConfData string, oldDirectives confDirectives,
) error {
	return job.regenReqForTest(port, confFile, oldConfData, RedisConfRenderItem{}).
		validateRegenConf(confData, oldDirectives)
}

func (job *RedisVersionUpdate) applyReplExpectationToConf(port int, confData string) string {
	return job.regenRequest(port).applyReplExpectationToConf(confData)
}

func TestValidateRegenConf(t *testing.T) {
	oldConf := liveConfAfterConfigRewrite
	oldDirectives := parseRedisConfDirectives(oldConf)
	goodConf := strings.Join([]string{
		"bind 1.1.1.1",
		"port 30000",
		"dir /data1/redis/30000/data",
		"requirepass \"xxxxpasswd\"",
		"masterauth \"xxxxpasswd\"",
		"replicaof 1.1.1.2 30000",
	}, "\n") + "\n"

	job := buildRegenJob("1.1.1.1", []int{30000})
	if err := job.validateRegenConf(
		30000, "/data1/redis/30000/redis.conf", goodConf, oldConf, oldDirectives); err != nil {
		t.Fatalf("valid conf rejected:%v", err)
	}

	cases := []struct {
		name    string
		conf    string
		wantErr string
	}{
		{
			name:    "leftover placeholder",
			conf:    strings.Replace(goodConf, "\"xxxxpasswd\"", "{{password}}", 1),
			wantErr: "unresolved placeholder",
		},
		{
			name:    "missing dir",
			conf:    "bind 1.1.1.1\nport 30000\nrequirepass \"xxxxpasswd\"\nreplicaof 1.1.1.2 30000\n",
			wantErr: "missing directive \"dir\"",
		},
		{
			name:    "wrong port",
			conf:    strings.Replace(goodConf, "port 30000", "port 30001", 1),
			wantErr: "mismatch",
		},
		{
			name:    "lost requirepass",
			conf:    strings.Replace(goodConf, "requirepass \"xxxxpasswd\"\n", "", 1),
			wantErr: "lost requirepass",
		},
		{
			name:    "changed requirepass",
			conf:    strings.Replace(goodConf, "requirepass \"xxxxpasswd\"", "requirepass otherpass", 1),
			wantErr: "would change requirepass",
		},
		{
			// 换个叶子目录, 而不是 /data1 -> /data: 后者在真有这条软链的机器上是同一目录
			name:    "moved data dir",
			conf:    strings.Replace(goodConf, "/data1/redis/30000/data", "/data1/redis/30000/data-moved", 1),
			wantErr: "would move dir",
		},
		{
			name:    "lost replication",
			conf:    strings.Replace(goodConf, "replicaof 1.1.1.2 30000\n", "", 1),
			wantErr: "lost replication",
		},
		{
			name:    "changed replication target",
			conf:    strings.Replace(goodConf, "replicaof 1.1.1.2 30000", "replicaof 3.3.3.3 30000", 1),
			wantErr: "lost replication",
		},
		{
			// 旧文件里根本没有 masterauth 之外的凭据变更时也要拦: 改了主从同步会认证失败
			name:    "changed masterauth",
			conf:    strings.Replace(goodConf, "masterauth \"xxxxpasswd\"", "masterauth otherpass", 1),
			wantErr: "would change masterauth",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			err := job.validateRegenConf(
				30000, "/data1/redis/30000/redis.conf", tc.conf, oldConf, oldDirectives)
			if err == nil {
				t.Fatalf("expected error containing %q, got nil", tc.wantErr)
			}
			if !strings.Contains(err.Error(), tc.wantErr) {
				t.Errorf("err = %v, want it to contain %q", err, tc.wantErr)
			}
		})
	}
}

// setupAliasedDataDir 造一份 /data1 -> /data 的现场: 返回真实数据盘与它的软链别名.
func setupAliasedDataDir(t *testing.T, port int) (realDataDir, aliasDataDir string) {
	t.Helper()
	root := t.TempDir()
	realDataDir = filepath.Join(root, "data")
	aliasDataDir = filepath.Join(root, "data1")
	if err := os.MkdirAll(filepath.Join(realDataDir, "redis", strconv.Itoa(port)), 0755); err != nil {
		t.Fatalf("mkdir failed:%v", err)
	}
	if err := os.Symlink(realDataDir, aliasDataDir); err != nil {
		t.Fatalf("symlink failed:%v", err)
	}
	return realDataDir, aliasDataDir
}

func TestSamePathValue(t *testing.T) {
	realDataDir, aliasDataDir := setupAliasedDataDir(t, 30000)
	realDir := filepath.Join(realDataDir, "redis", "30000", "data")
	aliasDir := filepath.Join(aliasDataDir, "redis", "30000", "data")

	cases := []struct {
		name string
		a, b string
		want bool
	}{
		// config rewrite 会给取值加引号, 不能因此判成换了目录
		{"quoted vs bare", "\"" + realDir + "\"", realDir, true},
		{"trailing slash", realDir + "/", realDir, true},
		{"symlinked data dir", realDir, aliasDir, true},
		{"quoted symlinked data dir", "\"" + realDir + "\"", aliasDir, true},
		{"different leaf", realDir, realDir + "-moved", false},
		{"one side empty", "", realDir, false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := samePathValue(tc.a, tc.b); got != tc.want {
				t.Errorf("samePathValue(%q,%q) = %v, want %v", tc.a, tc.b, got, tc.want)
			}
		})
	}
}

