func TestEnsureMasterAuthForReplica(t *testing.T) {
	// old_master 升级后跟随 new_master
	syncExpect := expectSyncMaster("1.1.1.1:30000", "1.1.1.2", "30000")
	// old_slave 升级: 停机前就是从库, 主库不变
	slaveExpect := replSnapshot{
		addr: "1.1.1.1:30000", role: consts.RedisSlaveRole, masterHost: "1.1.1.2", masterPort: "30000",
	}
	const withRepl = "port 30000\nrequirepass xxxxpasswd\nreplicaof 1.1.1.2 30000\n"

	cases := []struct {
		name        string
		clusterType string
		expect      replSnapshot
		conf        string
		want        string
		notWant     string
	}{
		{
			// dbconfig 里没有 masterauth, old_master 自己当主时磁盘上也没有:
			// 不补的话实例带着 replicaof 起来, 同步卡在 AUTH 上
			name:   "old master gets masterauth alongside replicaof",
			expect: syncExpect,
			conf:   withRepl,
			want:   "masterauth xxxxpasswd",
		},
		{
			// 同一个洞的另一半: config rewrite 静默失败过, 从库自己的 conf 就缺凭据
			name:   "old slave with replicaof but no masterauth",
			expect: slaveExpect,
			conf:   withRepl,
			want:   "masterauth xxxxpasswd",
		},
		{
			// old_master 曾经当过从库, 留下的凭据指向旧密码
			name:    "stale masterauth replaced when following a new master",
			expect:  syncExpect,
			conf:    "port 30000\nrequirepass xxxxpasswd\nmasterauth oldpass\nreplicaof 1.1.1.2 30000\n",
			want:    "masterauth xxxxpasswd",
			notWant: "oldpass",
		},
		{
			// 本次不改变它跟谁, 那条凭据也就轮不到这里做主
			name:   "stale masterauth kept when master does not change",
			expect: slaveExpect,
			conf:   "port 30000\nrequirepass xxxxpasswd\nmasterauth oldpass\nreplicaof 1.1.1.2 30000\n",
			want:   "masterauth oldpass",
		},
		{
			// config rewrite 对空密码实例写出的是 masterauth "", 指令在但取值是空的:
			// 只看指令存不存在会让兜底静默失效
			name:    "explicitly empty masterauth is filled in",
			expect:  slaveExpect,
			conf:    "port 30000\nrequirepass \"xxxxpasswd\"\nmasterauth \"\"\nreplicaof 1.1.1.2 30000\n",
			want:    "masterauth \"xxxxpasswd\"",
			notWant: "masterauth \"\"",
		},
		{
			name:    "no password cluster gets nothing",
			expect:  syncExpect,
			conf:    "port 30000\nrequirepass \"\"\nreplicaof 1.1.1.2 30000\n",
			notWant: "masterauth",
		},
		{
			// cluster 的凭据由切换流程 config set + rewrite, 配置文件不是它的来源
			name:        "cluster type is left alone",
			clusterType: consts.TendisTypePredixyRedisCluster,
			expect:      syncExpect,
			conf:        withRepl,
			notWant:     "masterauth",
		},
		{
			name:    "instance without replication needs no masterauth",
			expect:  replSnapshot{addr: "1.1.1.1:30000", role: consts.RedisMasterRole},
			conf:    "port 30000\nrequirepass xxxxpasswd\n",
			notWant: "masterauth",
		},
		{
			name:   "already correct masterauth is untouched",
			expect: syncExpect,
			conf:   "port 30000\nrequirepass xxxxpasswd\nmasterauth xxxxpasswd\nreplicaof 1.1.1.2 30000\n",
			want:   "masterauth xxxxpasswd",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			clusterType := tc.clusterType
			if clusterType == "" {
				clusterType = consts.TendisTypeTwemproxyRedisInstance
			}
			got := newRegenReqForTest(clusterType, tc.expect).ensureMasterAuthForReplica(tc.conf)
			if tc.want != "" && !strings.Contains(got, tc.want) {
				t.Errorf("conf missing %q:\n%s", tc.want, got)
			}
			if tc.notWant != "" && strings.Contains(got, tc.notWant) {
				t.Errorf("conf should not contain %q:\n%s", tc.notWant, got)
			}
			// 多写一条 redis 只认最后一行, 但文件里两条不同凭据之后谁读都会读错
			if count := strings.Count(got, "masterauth "); count > 1 {
				t.Errorf("masterauth appears %d times, want at most 1:\n%s", count, got)
			}
		})
	}
}

