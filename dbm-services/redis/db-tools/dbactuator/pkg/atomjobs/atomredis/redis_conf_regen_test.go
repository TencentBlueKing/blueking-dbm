func TestRegenConfFileWritesAndRestores(t *testing.T) {
	job := buildRegenJob("1.1.1.1", []int{30000})
	confFile := setupInstanceConf(t, 30000, "placeholder\n")
	instDir := filepath.Dir(confFile)
	liveConf := liveConfForInstDir(instDir)
	if err := os.WriteFile(confFile, []byte(liveConf), 0644); err != nil {
		t.Fatalf("rewrite conf failed:%v", err)
	}

	job.params.PortConfConfigs = map[string]RedisConfRenderItem{"30000": targetConfItem(instDir)}
	if err := job.regenConfFile(30000); err != nil {
		t.Fatalf("regenConfFile err:%v", err)
	}

	got, err := os.ReadFile(confFile)
	if err != nil {
		t.Fatalf("read conf failed:%v", err)
	}
	if strings.Contains(string(got), "slave-lazy-flush") {
		t.Errorf("stale directive kept:\n%s", got)
	}
	for _, want := range []string{
		"replica-lazy-flush yes", "maxmemory 8589934592", "requirepass xxxxpasswd", "replicaof 1.1.1.2 30000",
		// 旧配置里没有 masterauth, 重建时要补上, 否则重启后同步认证失败
		"masterauth xxxxpasswd",
	} {
		if !strings.Contains(string(got), want) {
			t.Errorf("regenerated conf missing %q:\n%s", want, got)
		}
	}
	backupFile, ok := job.confBackupFiles[30000]
	if !ok {
		t.Fatal("no backup recorded")
	}
	backup, err := os.ReadFile(backupFile)
	if err != nil {
		t.Fatalf("read backup failed:%v", err)
	}
	if string(backup) != liveConf {
		t.Errorf("backup is not the original conf:\n%s", backup)
	}

	// 起不来时回滚: 配置文件必须逐字节回到原样
	if err = job.restoreRedisConfFile(30000); err != nil {
		t.Fatalf("restoreRedisConfFile err:%v", err)
	}
	if got, err = os.ReadFile(confFile); err != nil {
		t.Fatalf("read conf failed:%v", err)
	}
	if string(got) != liveConf {
		t.Errorf("restore did not put the original conf back:\n%s", got)
	}
	if _, ok = job.confBackupFiles[30000]; ok {
		t.Error("backup entry should be dropped after restore")
	}
}

