	// 与运行态一致时放行
	goodConf := strings.Replace(conf, "replicaof 2.2.2.2 30000", "replicaof 1.1.1.2 30000", 1)
	if err = job.validateRegenConf(
		30000, "/data1/redis/30000/redis.conf", goodConf, oldConf,
		redisconf.ParseDirectives(oldConf)); err != nil {
		t.Errorf("conf matching runtime master rejected:%v", err)
	}
