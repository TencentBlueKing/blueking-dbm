// liveConfAfterConfigRewrite 一份 config rewrite 之后的 redis.conf 片段.
// 特点: 指令顺序被重排, 可重复指令是多行, maxmemory / replicaof 是运行态写进去的.
const liveConfAfterConfigRewrite = `# Redis configuration rewritten by CONFIG REWRITE
bind 1.1.1.1
port 30000
requirepass "xxxxpasswd"
masterauth "xxxxpasswd"
dir /data1/redis/30000/data
logfile /data1/redis/30000/redis.log
databases 2
maxmemory 8589934592
appendonly no
slave-lazy-flush yes
rename-command config confxx
rename-command flushdb cleandb
rename-command flushall cleanall
save 3600 1
save 300 100
client-output-buffer-limit normal 256mb 512mb 300
client-output-buffer-limit slave 2048mb 2048mb 300

# Generated by CONFIG REWRITE
replicaof 1.1.1.2 30000
`

func TestParseRedisConfDirectives(t *testing.T) {
	directives := ParseDirectives(liveConfAfterConfigRewrite)

	if got := directives.LastValue("port"); got != "30000" {
		t.Errorf("port = %q, want 30000", got)
	}
	if got := directives.LastValue("dir"); got != "/data1/redis/30000/data" {
		t.Errorf("dir = %q", got)
	}
	if got := directives.LastValue("maxmemory"); got != "8589934592" {
		t.Errorf("maxmemory = %q", got)
	}
	// 可重复指令必须保留全部取值, 不能被折叠成一条 (否则 flushall 会被悄悄取消改名)
	if got := len(directives["rename-command"]); got != 3 {
		t.Errorf("rename-command values = %d, want 3", got)
	}
	if got := len(directives["save"]); got != 2 {
		t.Errorf("save values = %d, want 2", got)
	}
	// 注释行不参与解析
	if directives.Has("#") || directives.Has("# redis") {
		t.Error("comment lines should be skipped")
	}
}

func TestEffectiveReplicationOf(t *testing.T) {
	cases := []struct {
		name      string
		conf      string
		wantKey   string
		wantValue string
	}{
		{"replicaof", "replicaof 1.1.1.2 30000\n", "replicaof", "1.1.1.2 30000"},
		{"slaveof", "slaveof 1.1.1.2 30000\n", "slaveof", "1.1.1.2 30000"},
		{"slaveof no one", "slaveof no one\n", "", ""},
		{"master", "port 30000\n", "", ""},
		{"commented out", "#replicaof 1.1.1.2 30000\n", "", ""},
		{
			// redis 把 slaveof/replicaof 当同一指令, 以文件最后一次出现为准:
			// 按指令名优先级取值会挑出 1.1.1.2, 也就看不出实例其实跟了 2.2.2.2
			name:      "replicaof then slaveof",
			conf:      "replicaof 1.1.1.2 30000\nslaveof 2.2.2.2 30000\n",
			wantKey:   "slaveof",
			wantValue: "2.2.2.2 30000",
		},
		{
			name:      "slaveof then replicaof",
			conf:      "slaveof 2.2.2.2 30000\nreplicaof 1.1.1.2 30000\n",
			wantKey:   "replicaof",
			wantValue: "1.1.1.2 30000",
		},
		{
			// 后面的 no one 取消了前面的主从关系
			name: "replicaof then slaveof no one",
			conf: "replicaof 1.1.1.2 30000\nslaveof no one\n",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			key, value := EffectiveReplicationOf(tc.conf)
			if key != tc.wantKey || value != tc.wantValue {
				t.Errorf("EffectiveReplicationOf = (%q,%q), want (%q,%q)",
					key, value, tc.wantKey, tc.wantValue)
			}
		})
	}
}

