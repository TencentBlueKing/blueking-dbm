// regenReqWithTargetPassword 一次"上游显式下发了目标密码"的重建请求.
// Expect 是停机前快照(wanted=false), 也就是本次不改变它跟谁
func regenReqWithTargetPassword(oldConfData string, target *string) Request {
	req := newRegenReqForTest(consts.TendisTypeTwemproxyRedisInstance, ReplState{
		Addr: "1.1.1.1:30000", Role: consts.RedisSlaveRole, MasterHost: "1.1.1.2", MasterPort: "30000",
	})
	req.OldConfData = oldConfData
	req.TargetPassword = target
	req.Steps = RefreshSteps
	return req
}

func TestValidateRegenConfTargetPassword(t *testing.T) {
	// 磁盘现状: requirepass 与 masterauth 都是 xxxxpasswd
	oldConf := liveConfAfterConfigRewrite
	confWithPass := func(requirepass, masterauth string) string {
		return strings.Join([]string{
			"bind 1.1.1.1",
			"port 30000",
			"dir /data1/redis/30000/data",
			"requirepass " + requirepass,
			"masterauth " + masterauth,
			"replicaof 1.1.1.2 30000",
		}, "\n") + "\n"
	}
	newPass, emptyPass, samePass := "newpasswd", "", "xxxxpasswd"

	cases := []struct {
		name string
		// target 上游下发的目标密码; follow 是探测结论"主库已经在用它了"
		target  *string
		follow  bool
		conf    string
		wantErr string
	}{
		{
			// 改密码时 masterauth 原样留着, 这就是渲染器该有的输出
			name:   "rendered with the delivered password",
			target: &newPass,
			conf:   confWithPass("newpasswd", "\"xxxxpasswd\""),
		},
		{
			// 改成无密码时同样不动 masterauth
			name:   "delivered empty password",
			target: &emptyPass,
			conf:   confWithPass("\"\"", "\"xxxxpasswd\""),
		},
		{
			// 下发的目标与磁盘一致, 等于没改密码
			name:   "target equals disk",
			target: &samePass,
			conf:   confWithPass("\"xxxxpasswd\"", "\"xxxxpasswd\""),
		},
		{
			// 下发了改密码, 渲染却还是旧的: 单据做了个寂寞, 必须拦
			name:    "target not rendered",
			target:  &newPass,
			conf:    confWithPass("\"xxxxpasswd\"", "\"xxxxpasswd\""),
			wantErr: "does not match the delivered target password",
		},
		{
			// 探测说主库还没改, 却把 masterauth 提前挪了过去: 从库下次重连就连不上
			name:    "masterauth moved ahead of the master",
			target:  &newPass,
			conf:    confWithPass("newpasswd", "newpasswd"),
			wantErr: "moved masterauth while the master is not on the new password yet",
		},
		{
			// 探测说主库已经改好, 凭据必须跟过去
			name:   "masterauth follows a master that already changed",
			target: &newPass,
			follow: true,
			conf:   confWithPass("newpasswd", "newpasswd"),
		},
		{
			// 该跟却没跟: 从库还拿旧密码去 AUTH 一台已经换了密码的主库
			name:    "masterauth left behind although the master changed",
			target:  &newPass,
			follow:  true,
			conf:    confWithPass("newpasswd", "\"xxxxpasswd\""),
			wantErr: "should have moved masterauth onto the new password",
		},
		{
			// 没下发目标密码时口径不变: 变了就是事故
			name:    "no target still rejects a change",
			conf:    confWithPass("newpasswd", "newpasswd"),
			wantErr: "would change requirepass",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			req := regenReqWithTargetPassword(oldConf, tc.target)
			req.MasterAuthFollowsPassword = tc.follow
			err := req.Validate(tc.conf)
			if tc.wantErr == "" {
				if err != nil {
					t.Fatalf("valid conf rejected:%v", err)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
				t.Errorf("err = %v, want it to contain %q", err, tc.wantErr)
			}
		})
	}
}

func TestRenderTargetConfWithTargetPassword(t *testing.T) {
	confFile := setupInstanceConf(t, 30000, "placeholder\n")
	instDir := filepath.Dir(confFile)
	oldConf := liveConfForInstDir(instDir)

	newPass := "newpasswd"
	req := regenReqWithTargetPassword(oldConf, &newPass)
	req.Item = targetConfItem(instDir)
	req.ConfFile = confFile
	// liveConfForInstDir 的实例目录是临时目录, dir 校验要按它来
	plan, err := req.Plan()
	if err != nil {
		t.Fatalf("Plan err:%v", err)
	}
	if !strings.Contains(plan.NewConf, "requirepass newpasswd") {
		t.Errorf("requirepass not rendered from the delivered target:\n%s", plan.NewConf)
	}
	// 旧配置里根本没有 masterauth, 而从库身份必须带一份凭据, 只能按新密码补.
	// 与"已有 masterauth 留着不动"不冲突: 这里没有可留的
	if !strings.Contains(plan.NewConf, "masterauth newpasswd") {
		t.Errorf("replica without masterauth should get one:\n%s", plan.NewConf)
	}
	if strings.Contains(plan.NewConf, "xxxxpasswd") {
		t.Errorf("old password left in the regenerated conf:\n%s", plan.NewConf)
	}
}

// TestRenderTargetConfMasterAuthFollowsProbe 改密码时 masterauth 渲染成什么, 由探测结论
// 说了算, 渲染自己不猜: 它看不见对端主库改到哪一步了.
//
// restart 模式下这份渲染结果会直接落盘、实例带着它重连, 所以两个方向都要正确 ——
// 主库还没改就挪过去, 或主库已经改了却不挪, 重连都会 AUTH 失败.
func TestRenderTargetConfMasterAuthFollowsProbe(t *testing.T) {
	cases := []struct {
		name   string
		follow bool
		want   string
	}{
		{name: "master still on the old password", follow: false, want: "masterauth \"xxxxpasswd\""},
		{name: "master already changed", follow: true, want: "masterauth newpasswd"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			confFile := setupInstanceConf(t, 30000, "placeholder\n")
			instDir := filepath.Dir(confFile)
			oldConf := liveConfForInstDir(instDir) + "masterauth \"xxxxpasswd\"\n"

			newPass := "newpasswd"
			req := regenReqWithTargetPassword(oldConf, &newPass)
			req.MasterAuthFollowsPassword = tc.follow
			req.Item = targetConfItem(instDir)
			req.ConfFile = confFile
			plan, err := req.Plan()
			if err != nil {
				t.Fatalf("Plan err:%v", err)
			}
			if count := strings.Count(plan.NewConf, "masterauth "); count != 1 {
				t.Errorf("masterauth appears %d times, want 1:\n%s", count, plan.NewConf)
			}
			if !strings.Contains(plan.NewConf, tc.want) {
				t.Errorf("want %q in the rendered conf:\n%s", tc.want, plan.NewConf)
			}
			if !strings.Contains(plan.NewConf, "requirepass newpasswd") {
				t.Errorf("requirepass not rendered from the delivered target:\n%s", plan.NewConf)
			}
		})
	}
}

