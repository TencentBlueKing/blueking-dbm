// LIST_FKS_ON_DB_SQL 拉取数据库内所有用户表的外键关系（parent → referenced）
// 用于"按表清理"场景做 FK 越界检查，%s 为数据库名
var LIST_FKS_ON_DB_SQL = `
USE [%s];
SELECT
    fk.name              AS fk_name,
    ps.name              AS parent_schema,
    pt.name              AS parent_table,
    rs.name              AS ref_schema,
    rt.name              AS ref_table
FROM sys.foreign_keys fk
JOIN sys.tables  pt ON pt.object_id = fk.parent_object_id
JOIN sys.schemas ps ON ps.schema_id = pt.schema_id
JOIN sys.tables  rt ON rt.object_id = fk.referenced_object_id
JOIN sys.schemas rs ON rs.schema_id = rt.schema_id
WHERE pt.is_ms_shipped = 0;
`

// LIST_SCHEMABOUND_REFS_SQL 查找 schema-bound 对象（带 SCHEMABINDING 的视图/UDF 等）
// 对用户表的引用。这类引用会阻止 DROP TABLE，必须在 drop 前提示用户。
// %s 为数据库名
var LIST_SCHEMABOUND_REFS_SQL = `
USE [%s];
SELECT
    referencing  = QUOTENAME(SCHEMA_NAME(o.schema_id)) + '.' + QUOTENAME(o.name)
                 + N' (' + o.type_desc + N')' COLLATE DATABASE_DEFAULT,
    referenced   = QUOTENAME(s2.name) + '.' + QUOTENAME(t.name) COLLATE DATABASE_DEFAULT
FROM sys.sql_expression_dependencies d
JOIN sys.objects  o  ON o.object_id  = d.referencing_id
JOIN sys.tables   t  ON t.object_id  = d.referenced_id
JOIN sys.schemas  s2 ON s2.schema_id = t.schema_id
WHERE d.is_schema_bound_reference = 1
  AND t.is_ms_shipped = 0
  AND o.type NOT IN ('U', 'S')  -- Exclude user tables and system tables as referencers, only return true schema-bound objects
`

// DELETE_TABLES_FOR_FK_BY_LIST 对指定表清单执行 DELETE 清理方案
// 第一个 %s: 数据库名
// DELETE_TABLES_FOR_FK_BY_LIST 对指定表清单执行 DELETE 清理方案
// 第一个 %s: 数据库名
// 第二个 %s: 由 Go 侧拼接的多行 INSERT INTO #T(...) 语句，注入待清理表清单
// 步骤：disable constraint -> disable trigger -> delete -> reseed identity ->
//
//	WITH CHECK CHECK CONSTRAINT ALL -> enable trigger
var DELETE_TABLES_FOR_FK_BY_LIST = `
USE [%s]
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRY
    BEGIN TRAN;

    IF OBJECT_ID('tempdb..#T') IS NOT NULL DROP TABLE #T;
    CREATE TABLE #T(
        object_id   int            NOT NULL,
        FullName    nvarchar(512)  NOT NULL,
        HasIdentity bit            NOT NULL
    );

    -- Inject target table list (generated by Go side)
    %s

    DECLARE @sql nvarchar(max) = N'';

    -- 1) Disable constraints on all target tables
    SELECT @sql += N'ALTER TABLE ' + FullName + N' NOCHECK CONSTRAINT ALL;' FROM #T;
    EXEC sp_executesql @sql;

    -- 2) Disable triggers on all target tables
    SET @sql = N'';
    SELECT @sql += N'ALTER TABLE ' + FullName + N' DISABLE TRIGGER ALL;' FROM #T;
    EXEC sp_executesql @sql;

    -- 3) Delete all data from target tables
    SET @sql = N'';
    SELECT @sql += N'DELETE FROM ' + FullName + N';' FROM #T;
    EXEC sp_executesql @sql;

    -- 4) Reseed identity for tables with identity columns
    SET @sql = N'';
    SELECT @sql += N'DBCC CHECKIDENT (''' + FullName + N''', RESEED, 0) WITH NO_INFOMSGS;'
    FROM #T WHERE HasIdentity = 1;
    EXEC sp_executesql @sql;

    -- 5) Re-enable constraints and force validation to re-trust FKs
    SET @sql = N'';
    SELECT @sql += N'ALTER TABLE ' + FullName + N' WITH CHECK CHECK CONSTRAINT ALL;' FROM #T;
    EXEC sp_executesql @sql;

    -- 6) Re-enable triggers
    SET @sql = N'';
    SELECT @sql += N'ALTER TABLE ' + FullName + N' ENABLE TRIGGER ALL;' FROM #T;
    EXEC sp_executesql @sql;

    COMMIT TRAN;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRAN;
    THROW;
END CATCH;
`

