var DELETE_TABLES_FOR_FK = `
/* =========================================================
   Plan A: Full DB purge with DELETE (safe/default)
   - Disable constraints/triggers
   - DELETE all target tables
   - Optional identity reseed
   - Re-enable constraints with trust (WITH CHECK CHECK)
   ========================================================= */
USE [%s]
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRY
    BEGIN TRAN;

    ---------------------------------------------------------
    -- 0) Build target table list (exclude what you want to keep)
    ---------------------------------------------------------
    IF OBJECT_ID('tempdb..#T') IS NOT NULL DROP TABLE #T;

    SELECT
        t.object_id,
        FullName = QUOTENAME(s.name) + '.' + QUOTENAME(t.name),
        HasIdentity =
            CASE WHEN EXISTS (
                SELECT 1
                FROM sys.identity_columns ic
                WHERE ic.object_id = t.object_id
            ) THEN 1 ELSE 0 END
    INTO #T
    FROM sys.tables t
    JOIN sys.schemas s ON s.schema_id = t.schema_id
    WHERE t.is_ms_shipped = 0
      AND NOT (s.name = 'dbo' AND t.name = '__EFMigrationsHistory'); -- keep EF Core migration history table

    ---------------------------------------------------------
    -- 1) Disable constraint checks
    ---------------------------------------------------------
    DECLARE @sql nvarchar(max) = N'';
    SELECT @sql += N'ALTER TABLE ' + FullName + N' NOCHECK CONSTRAINT ALL;'
    FROM #T;
    EXEC sp_executesql @sql;

    ---------------------------------------------------------
    -- 2) Disable triggers
    ---------------------------------------------------------
    SET @sql = N'';
    SELECT @sql += N'ALTER TABLE ' + FullName + N' DISABLE TRIGGER ALL;'
    FROM #T;
    EXEC sp_executesql @sql;

    ---------------------------------------------------------
    -- 3) Delete data from all target tables
    ---------------------------------------------------------
    SET @sql = N'';
    SELECT @sql += N'DELETE FROM ' + FullName + N';'
    FROM #T;
    EXEC sp_executesql @sql;

    ---------------------------------------------------------
    -- 4) Optional: reseed identity to 0 (next insert starts at 1)
    ---------------------------------------------------------
    SET @sql = N'';
    SELECT @sql += N'DBCC CHECKIDENT (''' + FullName + N''', RESEED, 0) WITH NO_INFOMSGS;'
    FROM #T
    WHERE HasIdentity = 1;
    EXEC sp_executesql @sql;

    ---------------------------------------------------------
    -- 5) Re-enable constraints and re-trust them
    ---------------------------------------------------------
    SET @sql = N'';
    SELECT @sql += N'ALTER TABLE ' + FullName + N' WITH CHECK CHECK CONSTRAINT ALL;'
    FROM #T;
    EXEC sp_executesql @sql;

    ---------------------------------------------------------
    -- 6) Re-enable triggers
    ---------------------------------------------------------
    SET @sql = N'';
    SELECT @sql += N'ALTER TABLE ' + FullName + N' ENABLE TRIGGER ALL;'
    FROM #T;
    EXEC sp_executesql @sql;

    COMMIT TRAN;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRAN;
    THROW;
END CATCH;

`

