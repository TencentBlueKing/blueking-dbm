var MainConfig *mainConfig
var SinkerConfigs []*SinkerConfig

const (
	// OnMissingDatasourceSkip datasource 不存在时跳过该入库项
	OnMissingDatasourceSkip = "skip"
	// OnMissingDatasourceFail datasource 不存在时启动失败
	OnMissingDatasourceFail = "fail"
)

// DefaultsSinkerFile 内置默认入库项生成的文件名，由程序维护，不要手工修改。
// 需要个性化调整时，另外写一个 data.xxx.yaml，同 key 的项会整项覆盖这里的默认项。
const DefaultsSinkerFile = "data.defaults.yaml"

const defaultsFileHeader = `# Code generated by db-event-consumer --enable-defaults. DO NOT EDIT.
# 本文件由程序根据内置默认入库项(pkg/config/builtin_sinkers.go)生成，每次启动都会覆盖重写。
# 需要个性化调整某个入库项时，请另外新建一个 data.xxx.yaml，
# 把该项完整复制过去再改，同 key(model_table + group_id_suffix) 的项会整项覆盖本文件里的默认项。
`

func init() {
	MainConfig = &mainConfig{}
	SinkerConfigs = make([]*SinkerConfig, 0)

	// 先注册内置默认入库项(依赖 builtinSinkers 包级变量和 sinker 包，均已就绪)，
	// 顺序在这里显式保证，不依赖文件名字母序
	initDefaultSinker()

	_ = sinker.RegisterModelWriteType(&sinker.MysqlWriter{})
	_ = sinker.RegisterModelWriteType(&sinker.XormWriter{})
	_ = sinker.RegisterModelWriteType(&sinker.MysqlRawWriter{})
	_ = sinker.RegisterModelWriteType(&sinker.DorisWriter{})
	_ = sinker.RegisterModelWriteType(&sinker.DorisHttpWriter{})
}

type mainConfig struct {
	Log        *LogConfig           `yaml:"log"`
	KafkaInfo  *KafkaMeta           `yaml:"kafka_info"`
	BkmApiInfo *BkmApiInfo          `yaml:"bkm_api_info"`
	BkmReport  *base.BKReportConfig `yaml:"bkm_report"`
	OtelPort   int                  `yaml:"otel_port"`
	// OnMissingDatasource 入库项引用的 datasource 在 datasource.yaml 里不存在时的处理方式，
	// skip(默认): 跳过该入库项并打 WARN; fail: 启动失败
	OnMissingDatasource string `yaml:"on_missing_datasource"`
}

// InitConfig 加载主配置和入库项配置。
// enableDefaults=true 时，先用内置默认入库项覆盖重写 data.defaults.yaml，再加载所有 data.*.yaml
func InitConfig(configPath string, enableDefaults bool) error {
	mainConfigFile, err := InitMainConfig(configPath)
	if err != nil {
		return err
	}
	if enableDefaults {
		if err = GenerateDefaultsFile(filepath.Dir(mainConfigFile)); err != nil {
			return err
		}
	}
	SinkerConfigs, err = InitSinkerConfig(mainConfigFile)
	if err != nil {
		return err
	}
	return nil
}

func InitMainConfig(configPath string) (configFile string, err error) {
	if !filepath.IsAbs(configPath) {
		cwd, err := os.Getwd()
		if err != nil {
			return "", err
		}
		configPath = filepath.Join(cwd, configPath)
	}

	content, err := os.ReadFile(configPath)
	if err != nil {
		return "", err
	}

	if err = yaml.Unmarshal(content, MainConfig); err != nil {
		return "", errors.WithMessagef(err, "parse %s", configPath)
	}
	if MainConfig.OnMissingDatasource == "" {
		MainConfig.OnMissingDatasource = OnMissingDatasourceSkip
	}
	if !lo.Contains([]string{OnMissingDatasourceSkip, OnMissingDatasourceFail}, MainConfig.OnMissingDatasource) {
		return "", errors.Errorf("invalid on_missing_datasource: %s", MainConfig.OnMissingDatasource)
	}
	return configPath, nil
}

// GenerateDefaultsFile 把内置默认入库项写入 <configDir>/data.defaults.yaml。
// 每次启动都覆盖重写，保证新版本新增的入库项在所有环境自动生效
func GenerateDefaultsFile(configDir string) error {
	buf, err := yaml.Marshal(builtinSinkers)
	if err != nil {
		return errors.WithMessage(err, "marshal builtin sinkers")
	}
	target := filepath.Join(configDir, DefaultsSinkerFile)
	content := append([]byte(defaultsFileHeader), buf...)
	if err = os.WriteFile(target, content, 0644); err != nil {
		return errors.WithMessagef(err, "write %s", target)
	}
	return nil
}

// InitSinkerConfig 加载 <configDir>/data.*.yaml 里的入库项配置。
// 配置格式是入库项列表(list)，字段见 SinkerConfig。
//
// data.defaults.yaml 作为默认项基底(由 --enable-defaults 生成)，
// 其它 data.xxx.yaml 里 key(model_table + group_id_suffix) 相同的项会整项覆盖它，
// key 不存在的则作为新增入库项。
//
// 为了避免生效结果取决于文件名排序，以下情况直接报错：
//   - 同一个文件里出现重复 key
//   - 两个非 defaults 文件里出现相同 key
func InitSinkerConfig(mainConfFile string) ([]*SinkerConfig, error) {
	configDir := filepath.Dir(mainConfFile)
	files, err := filepath.Glob(filepath.Join(configDir, "data.*.yaml"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)

	var defaultSinkers []*SinkerConfig
	var userSinkers []*SinkerConfig
	// key -> 来源文件，用于检测多个用户配置文件里的重复 key
	userKeyFrom := make(map[string]string)

	for _, f := range files {
		sinkers, err := loadSinkerFile(f)
		if err != nil {
			return nil, err
		}
		if filepath.Base(f) == DefaultsSinkerFile {
			defaultSinkers = sinkers
			continue
		}
		for _, s := range sinkers {
			if from, ok := userKeyFrom[s.Key()]; ok {
				return nil, errors.Errorf("duplicate sinker [%s] in %s and %s, "+
					"please keep only one", s.Key(), from, filepath.Base(f))
			}
			userKeyFrom[s.Key()] = filepath.Base(f)
		}
		userSinkers = append(userSinkers, sinkers...)
	}

	// defaults 为基底，用户配置整项覆盖同 key 项，其余追加
	var allSinkers []*SinkerConfig
	userByKey := lo.SliceToMap(userSinkers, func(s *SinkerConfig) (string, *SinkerConfig) {
		return s.Key(), s
	})
	overridden := make(map[string]struct{})
	for _, d := range defaultSinkers {
		if u, ok := userByKey[d.Key()]; ok {
			allSinkers = append(allSinkers, u)
			overridden[d.Key()] = struct{}{}
			continue
		}
		allSinkers = append(allSinkers, d)
	}
	for _, u := range userSinkers {
		if _, ok := overridden[u.Key()]; ok {
			continue
		}
		allSinkers = append(allSinkers, u)
	}

	if err = finalizeSinkers(allSinkers); err != nil {
		return nil, err
	}
	if len(allSinkers) == 0 {
		return nil, errors.Errorf("no sinker configured, "+
			"please run with --enable-defaults to generate %s, or provide data.xxx.yaml in %s",
			DefaultsSinkerFile, configDir)
	}
	return allSinkers, nil
}

// loadSinkerFile 读取单个入库项配置文件，并检查文件内重复 key
func loadSinkerFile(file string) ([]*SinkerConfig, error) {
	content, err := os.ReadFile(file)
	if err != nil {
		return nil, errors.WithMessagef(err, "read %s", file)
	}
	var sinkers []*SinkerConfig
	if err = yaml.Unmarshal(content, &sinkers); err != nil {
		return nil, errors.WithMessagef(err, "parse %s", file)
	}
	seen := make(map[string]struct{})
	for _, s := range sinkers {
		if s == nil {
			return nil, errors.Errorf("%s contains empty sinker item", filepath.Base(file))
		}
		if s.ModelTable == "" {
			return nil, errors.Errorf("%s: model_table is required", filepath.Base(file))
		}
		if _, ok := seen[s.Key()]; ok {
			return nil, errors.Errorf("duplicate sinker [%s] in %s", s.Key(), filepath.Base(file))
		}
		seen[s.Key()] = struct{}{}
	}
	return sinkers, nil
}

// finalizeSinkers 补默认值并做合法性校验
func finalizeSinkers(sinkers []*SinkerConfig) error {
	checkDup := make(map[string]struct{})
	for _, s := range sinkers {
		if s.StrictSchema == nil {
			s.StrictSchema = &cst.PtrTrue
		}
		// 使用 topic/bk_collector_name/bk_data_id/group_id_suffix 组合生成唯一名称
		name := fmt.Sprintf("%s-%s-%d-%s", s.Topic, s.BkCollectorName, s.BkDataId, s.GroupIdSuffix)
		if _, ok := checkDup[name]; ok {
			return errors.Errorf("duplicate sinker name %s", name)
		}
		checkDup[name] = struct{}{}

		if s.WriteMode == "" {
			s.WriteMode = cst.ModeReplace
		}
		if !lo.Contains([]string{cst.ModeInsertIgnore, cst.ModeInsert, cst.ModeUpsert, cst.ModeReplace}, s.WriteMode) {
			return errors.Errorf("invalid write_mode: %s", s.WriteMode)
		}
		if s.Topic == "" && s.BkDataId == 0 && s.BkCollectorName == "" {
			return errors.Errorf("sinker [%s]: topic or bk_data_id or bk_collector_name must be set", s.Key())
		}
	}
	return nil
}

// EffectiveSinkersYaml 合并后最终生效的入库项配置，用于启动日志和 /debug/config
func EffectiveSinkersYaml() string {
	buf, err := yaml.Marshal(SinkerConfigs)
	if err != nil {
		return fmt.Sprintf("marshal effective sinkers failed: %v", err)
	}
	return string(buf)
}

// SinkerKeys 当前生效的入库项 key 列表
func SinkerKeys() string {
	keys := lo.Map(SinkerConfigs, func(s *SinkerConfig, _ int) string {
		return s.Key()
	})
	return strings.Join(keys, ",")
}
